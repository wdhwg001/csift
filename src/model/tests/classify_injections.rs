//! classify(): the isMeta INJECTION templates - the text the harness writes into a turn
//! wearing a user record's clothes, and the authorship flag that keeps a person's own
//! message out of the family.

use super::*;

// -- the isMeta injection templates + the isMeta image exclusion --

#[test]
fn classify_injection_template_variants() {
    // Stop-hook feedback (the dominant shape: feedback + the edit-failed-retry body).
    // The opening sentence decides: the feedback arm is tested before the retry one.
    let stop = parse(
        r#"{"type":"user","isMeta":true,"message":{"role":"user","content":"Stop hook feedback:\nThe last Edit failed because the target file was modified."}}"#,
    );
    assert_eq!(
        stop.classify(&ClassifyCtx::top_level()),
        vec![Class::HookFeedback]
    );
    // <local-command-caveat> wrapper (isMeta): the slash-command EXECUTOR writes it, not
    // a hook, so it sits in the command family.
    let caveat = parse(
        r#"{"type":"user","isMeta":true,"message":{"role":"user","content":"<local-command-caveat>Caveat: the messages below were generated by a command.</local-command-caveat>"}}"#,
    );
    assert_eq!(
        caveat.classify(&ClassifyCtx::top_level()),
        vec![Class::CommandCaveat]
    );
    // The bare edit-failed-retry notice (matched anywhere, because the harness appends
    // it to the failed call's own result rather than writing a standalone prompt): a
    // redo nudge, so it sits in the enforce family.
    let edit = parse(
        r#"{"type":"user","isMeta":true,"message":{"role":"user","content":"The last Edit failed because the target file was modified since it was read."}}"#,
    );
    assert_eq!(
        edit.classify(&ClassifyCtx::top_level()),
        vec![Class::EnforceRetry]
    );
    // The same words with NO isMeta are a person asking about the notice, and they keep
    // the person's leaf: every template arm reads text, so the authorship flag is what
    // separates the two populations.
    let asking = parse(
        r#"{"type":"user","message":{"role":"user","content":"The last Edit failed because the target file was modified since it was read."}}"#,
    );
    assert_eq!(
        asking.classify(&ClassifyCtx::top_level()),
        vec![Class::UserMessage]
    );
}

#[test]
fn classify_ismeta_image_record_takes_the_context_image_leaf() {
    // An isMeta `[Image: ...]` pseudo-record is the harness's stand-in for a pasted or
    // attached image. It was EXCLUDED while the taxonomy had no leaf to put it under -
    // better silent than mislabeled `user.message` - and `harness.context.image` is that
    // leaf. Both openings the builder writes land on it.
    for content in [
        "[Image: source: /Users/dev/.claude/image-cache/abc.png]",
        "[Image source: /Users/dev/.claude/image-cache/abc.png]",
        "[Image: 1024x768]",
    ] {
        let line = serde_json::json!({
            "type": "user",
            "isMeta": true,
            "message": {"role": "user", "content": content},
        })
        .to_string();
        let r = parse(&line);
        assert_eq!(
            r.classify(&ClassifyCtx::top_level()),
            vec![Class::ContextImage],
            "{content}"
        );
    }
    // A record merely QUOTING the reference mid-prose keeps its own leaf: the arm is
    // content-start anchored like every other template.
    let quoting = parse(
        r#"{"type":"user","message":{"role":"user","content":"the harness writes [Image: 1024x768] for a paste"}}"#,
    );
    assert_eq!(
        quoting.classify(&ClassifyCtx::top_level()),
        vec![Class::UserMessage]
    );
}

/// The harness's NINE turn continuations, written out here as the producer writes them
/// rather than read from the constant under test: a test that iterated the crate's own
/// list would still pass with that list emptied.
const CONTINUATIONS: &[&str] = &[
    "The previous response failed to produce a valid tool call. Please retry the tool call now.",
    "Your tool call was malformed and could not be parsed. Please retry.",
    "[Your previous response had no visible output. Please continue and produce a user-visible response.]",
    "The PermissionDenied hook indicated you may retry this tool call.",
    "Your response above was stopped by a safety classifier \u{2014} this is not a tool or API error. The rest of it was withheld, and tool calls in it that had not finished did not run. Do not produce that content again, even reworded.",
    "Your response above was stopped by a safety classifier \u{2014} this is not a tool or API error. The rest of it was withheld, and tool calls in it that had not finished did not run. Do not produce that content again, even reworded. Exception: a tool call whose result reads \"Interrupted\" was already running when the response was stopped; it may have partially or fully completed.",
    "Output token limit hit. Resume directly \u{2014} no apology, no recap of what you were doing. Pick up mid-thought if that is where the cut happened. Break remaining work into smaller pieces.",
    "Your response above was cut off mid-stream. Resume directly from where it stops \u{2014} no apology, no recap. If none of it survived, answer the request from the start.",
    "Your response above was cut off mid-stream and only your next message is delivered. Write the complete response again from the start \u{2014} no apology, no mention of the cut-off.",
];

fn user_record(content: &str, is_meta: bool) -> Record {
    let mut line = serde_json::json!({
        "type": "user",
        "message": {"role": "user", "content": content},
    });
    if is_meta {
        line["isMeta"] = serde_json::Value::Bool(true);
    }
    parse(&line.to_string())
}

#[test]
fn every_turn_continuation_is_enforce_retry_and_the_same_words_typed_are_the_person() {
    for text in CONTINUATIONS {
        assert_eq!(
            user_record(text, true).classify(&ClassifyCtx::top_level()),
            vec![Class::EnforceRetry],
            "{text}"
        );
        // The authorship flag is the whole guard: a person QUOTING a continuation -
        // asking why the harness sent it - keeps `user.message` and opens their turn.
        let typed = user_record(text, false);
        assert_eq!(
            typed.classify(&ClassifyCtx::top_level()),
            vec![Class::UserMessage],
            "{text}"
        );
        assert!(typed.opens_turn(), "a typed message opens its turn: {text}");
        assert!(
            !user_record(text, true).opens_turn(),
            "a continuation opens no turn: {text}"
        );
    }
}

#[test]
fn a_message_that_merely_opens_with_a_continuation_is_not_one() {
    // WHOLE-message equality, never a prefix: the harness's own recogniser tests its
    // list that way, and these are complete bodies. A longer body opening with one is a
    // record quoting it.
    let longer = format!("{} And then explain why.", CONTINUATIONS[1]);
    assert!(
        user_record(&longer, true)
            .classify(&ClassifyCtx::top_level())
            .is_empty(),
        "a longer body carries no leaf"
    );
    // The interrupted classifier-stop form is the plain one plus a fixed tail, so the
    // plain one plus ANY other tail is not a continuation either.
    let wrong_tail = format!("{} Exception: something else.", CONTINUATIONS[4]);
    assert!(
        user_record(&wrong_tail, true)
            .classify(&ClassifyCtx::top_level())
            .is_empty(),
        "the tail is matched by equality, not by its opening word"
    );
}

#[test]
fn a_bundled_skill_body_with_no_directory_line_still_takes_the_skill_leaf() {
    // The registrar prepends the directory line only for a skill that ships FILES, so a
    // bundled body arrives bare and the leaf answers to its own head instead.
    let bare = user_record(
        "# Workflow authoring reference\n\nA workflow structures work across many agents.",
        true,
    );
    assert_eq!(
        bare.classify(&ClassifyCtx::top_level()),
        vec![Class::ContextSkill]
    );
    // The prefixed form is the same leaf, which is the point of the second head.
    let prefixed = user_record(
        "Base directory for this skill: /Users/dev/skills/demo",
        true,
    );
    assert_eq!(
        prefixed.classify(&ClassifyCtx::top_level()),
        vec![Class::ContextSkill]
    );
    // A person writing ABOUT the reference keeps their own leaf and their own turn: the
    // head is matched at content start under the authorship guard, like every template.
    let typed = user_record(
        "# Workflow authoring reference\n\nA workflow structures work across many agents.",
        false,
    );
    assert_eq!(
        typed.classify(&ClassifyCtx::top_level()),
        vec![Class::UserMessage]
    );
    assert!(typed.opens_turn());
    // And a body that merely MENTIONS the head mid-prose is not one either.
    let quoting = user_record("the skill opens # Workflow authoring reference", true);
    assert!(quoting.classify(&ClassifyCtx::top_level()).is_empty());
}
