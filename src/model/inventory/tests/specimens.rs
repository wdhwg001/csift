//! One hand-written jsonl line per row, walked back through the REAL engine. A table
//! that records a mapping is only worth the rows an actual record reaches, so these
//! are the assertions that would fail if a family arm and its row drifted apart.

use super::*;

/// The leaf set one hand-written jsonl line classifies to, under a bare top-level
/// context - the same entry point every surface takes.
fn labels(line: &str) -> Vec<Class> {
    serde_json::from_str::<Record>(line)
        .expect("valid record")
        .classify(&ClassifyCtx::top_level())
}

