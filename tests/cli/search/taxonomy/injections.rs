fn u(n: u32) -> String {
    format!("11111111-2222-4333-8444-{n:012}")
}

/// One isMeta `type:"user"` line parented to the line above it, carrying `body` as its
/// whole content and whatever `extra` top-level keys the template needs.
fn meta_line(n: u32, extra: &str, body: &str) -> String {
    let content = serde_json::to_string(body).expect("json string");
    format!(
        r#"{{"type":"user","uuid":"{uuid}","parentUuid":"{parent}","timestamp":"2026-06-07T05:00:{n:02}.000Z","cwd":"/Users/dev/inject-project","version":"2.1.258","userType":"external","isMeta":true{extra},"message":{{"role":"user","content":{content}}}}}"#,
        uuid = u(n),
        parent = u(n - 1),
    )
}

/// One `type:"user"` line whose content is a BLOCK ARRAY, isMeta or not.
fn block_line(n: u32, meta: bool, blocks: &str) -> String {
    let flag = if meta { r#","isMeta":true"# } else { "" };
    format!(
        r#"{{"type":"user","uuid":"{uuid}","parentUuid":"{parent}","timestamp":"2026-06-07T05:00:{n:02}.000Z","cwd":"/Users/dev/inject-project","version":"2.1.258","userType":"external"{flag},"message":{{"role":"user","content":[{blocks}]}}}}"#,
        uuid = u(n),
        parent = u(n - 1),
    )
}

