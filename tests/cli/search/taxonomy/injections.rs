//! The isMeta INJECTION family: text Claude Code writes into the conversation shaped
//! exactly like the operator's own message, one fixed template per producer.
//!
//! One fixture line per template the shape inventory advertises, plus the records that are
//! classified by a FIELD rather than by prose (the human relay, the two inbound relays, the
//! image-only record, the fired scheduler prompt) and the ones that must NOT be claimed (a
//! person quoting a template, an isMeta record matching no template at all, a document-only
//! record and a non-isMeta image-only one).
//!
//! The chain is linear - every record is parented to the one above it - so every line is
//! LIVE and the survival axis never suppresses a unit the assertions look for.
//!
//! A PAIRED ROOT: the ONE fixture lives here and the cases sit in three children named
//! for what they assert - `leaves` (which leaf a template reaches, and which shapes take
//! none), `edges` (what each injection was written for) and `people` (the records that
//! are a person or another session underneath). Every case builds the same transcript, so
//! a LINE NUMBER an assertion names means the same record in all three.

