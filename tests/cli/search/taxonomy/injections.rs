/// The per-leaf record counts a `--count-by label` census prints, as a map.
fn census(stdout: &str) -> std::collections::HashMap<String, usize> {
    let mut out = std::collections::HashMap::new();
    for line in stdout.lines() {
        let mut it = line.split_whitespace();
        let (Some(n), Some(key)) = (it.next(), it.next()) else {
            continue;
        };
        if let Ok(n) = n.parse::<usize>() {
            out.insert(key.to_string(), n);
        }
    }
    out
}

/// The first hit of the first exchange a json search stream carries.
fn first_hit(stdout: &str) -> serde_json::Value {
    let rows = json_rows(stdout, "exchange");
    assert!(!rows.is_empty(), "no exchange row:\n{stdout}");
    rows[0]["hits"][0].clone()
}

